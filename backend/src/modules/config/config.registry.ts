/**
 * Registry of parameter tables managed by the config module.
 *
 * Each entry describes one Prisma model: which columns can be edited, their
 * type and label. The API builds validation and the admin UI builds its forms
 * from this metadata, so adding a new parameter table only needs a Prisma
 * model plus one entry here.
 */
export type FieldType = "string" | "text" | "number" | "boolean" | "color";

export interface FieldDef {
  name: string;
  label: string;
  type: FieldType;
  required?: boolean;
  /** Hint shown under the input in the admin UI. */
  help?: string;
}

export interface TableDef {
  /** URL key: /api/config/tables/:key */
  key: string;
  label: string;
  description: string;
  /** Prisma client delegate name, e.g. "incidentCategory". */
  model: string;
  /** Primary key column. */
  idField: string;
  /**
   * true  → the id is generated by the database (uuid) and is not editable.
   * false → the id is a business code typed on create, then immutable.
   */
  idGenerated: boolean;
  orderBy: Record<string, "asc" | "desc">[];
  fields: FieldDef[];
}

